// Generates src/gen/cards-data.ts from data/cards.tsv (the authoritative card
// catalog, copied from the C# repo — never author card data by hand).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tsv = readFileSync(join(root, 'data/cards.tsv'), 'utf8');

const lines = tsv.split('\n').filter((l) => l.trim().length > 0);
const header = lines[0].split('\t');
const expected = ['Id', 'ActionType', 'Color', 'Size', 'BoostNumber', 'EffectFamily', 'EffectText'];
if (header.length !== 7 || header.some((h, i) => h.trim() !== expected[i])) {
  throw new Error(`cards.tsv header mismatch: ${header.join('|')}`);
}

const cards = lines.slice(1).map((line, i) => {
  const f = line.replace(/\r$/, '').split('\t');
  if (f.length !== 7) throw new Error(`cards.tsv line ${i + 2}: expected 7 fields, got ${f.length}`);
  return {
    id: Number(f[0]),
    actionType: f[1],
    color: f[2],
    size: Number(f[3]),
    boostNumber: Number(f[4]),
    effectFamily: f[5],
    effectText: f[6],
  };
});
if (cards.length !== 108) throw new Error(`expected 108 cards, got ${cards.length}`);

const out = `// GENERATED by scripts/build-card-data.mjs from data/cards.tsv — do not edit.
import type { Card } from '../engine/types';

export const CARDS: readonly Card[] = ${JSON.stringify(cards, null, 2)} as const;
`;
mkdirSync(join(root, 'src/gen'), { recursive: true });
writeFileSync(join(root, 'src/gen/cards-data.ts'), out);
console.log(`gen-cards: wrote ${cards.length} cards`);
